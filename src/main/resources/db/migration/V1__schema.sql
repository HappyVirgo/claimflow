CREATE TABLE policy (
    id               BIGINT PRIMARY KEY,
    policy_number    VARCHAR(32)    NOT NULL UNIQUE,
    line_of_business VARCHAR(16)    NOT NULL,
    effective_date   DATE           NOT NULL,
    expiration_date  DATE           NOT NULL,
    cancelled        BOOLEAN        NOT NULL,
    coverage_limit   DECIMAL(14, 2) NOT NULL,
    deductible       DECIMAL(14, 2) NOT NULL,
    coverages        VARCHAR(255)   NOT NULL
);

CREATE TABLE claimant (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(100) NOT NULL,
    last_name  VARCHAR(100) NOT NULL,
    email      VARCHAR(255) NOT NULL UNIQUE,
    phone      VARCHAR(32)
);

CREATE TABLE claim (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_number    VARCHAR(32)    NOT NULL UNIQUE,
    policy_id       BIGINT         NOT NULL REFERENCES policy (id),
    claimant_id     BIGINT         NOT NULL REFERENCES claimant (id),
    claim_type      VARCHAR(16)    NOT NULL,
    status          VARCHAR(32)    NOT NULL,
    loss_date       DATE           NOT NULL,
    reported_date   DATE           NOT NULL,
    description     VARCHAR(4000)  NOT NULL,
    risk_score      DOUBLE PRECISION,
    triage_report   VARCHAR(8000),
    payable_amount  DECIMAL(14, 2),
    approved_amount DECIMAL(14, 2),
    paid_amount     DECIMAL(14, 2),
    decision_reason VARCHAR(1000),
    version         BIGINT         NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_claim_policy_loss ON claim (policy_id, loss_date);
CREATE INDEX idx_claim_claimant_loss ON claim (claimant_id, loss_date);
CREATE INDEX idx_claim_status ON claim (status);

CREATE TABLE claim_line_item (
    claim_id    BIGINT         NOT NULL REFERENCES claim (id),
    seq         INT            NOT NULL,
    coverage    VARCHAR(32)    NOT NULL,
    description VARCHAR(500)   NOT NULL,
    amount      DECIMAL(14, 2) NOT NULL,
    PRIMARY KEY (claim_id, seq)
);

CREATE TABLE claim_document (
    claim_id     BIGINT       NOT NULL REFERENCES claim (id),
    seq          INT          NOT NULL,
    doc_type     VARCHAR(32)  NOT NULL,
    file_name    VARCHAR(255) NOT NULL,
    content_type VARCHAR(100) NOT NULL,
    size_bytes   BIGINT       NOT NULL,
    PRIMARY KEY (claim_id, seq)
);

CREATE TABLE adjuster_note (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id   BIGINT        NOT NULL REFERENCES claim (id),
    author     VARCHAR(100)  NOT NULL,
    body       VARCHAR(4000) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE audit_event (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id    BIGINT        NOT NULL REFERENCES claim (id),
    from_status VARCHAR(32),
    to_status   VARCHAR(32)   NOT NULL,
    action      VARCHAR(32)   NOT NULL,
    actor       VARCHAR(100)  NOT NULL,
    detail      VARCHAR(2000),
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_audit_claim ON audit_event (claim_id, id);
